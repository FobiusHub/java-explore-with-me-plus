package ru.practicum.ewm.service.event.exception;

import lombok.Builder;
import org.springframework.http.HttpStatus;

/**
 * Стандартизированный объект для представления ошибок в API.
 * Используется для единообразного формата ответов при возникновении исключений.
 *
 * <p>Содержит всю необходимую информацию для диагностики и обработки ошибок
 * на стороне клиента, включая список ошибок валидации, сообщение, причину,
 * HTTP-статус и временную метку.</p>
 *
 * <p>Этот record соответствует спецификации API для формата ошибок.</p>
 *
 * @see HttpStatus
 * @see Error
 */
@Builder
public record ApiError(
		/*
		 * Список отдельных ошибок валидации.
		 * Может быть null, если ошибка не связана с валидацией полей.
		 * Каждый элемент содержит информацию о конкретном нарушении валидации.
		 */
//		List<Error> errors,

		/*
		 * Детальное сообщение об ошибке, описывающее, что именно пошло не так.
		 */
		String message,

		/*
		 * Общее описание причины ошибки в человекочитаемом формате.
		 * Соответствует стандартным формулировкам API (например, "Incorrectly made request").
		 */
		String reason,

		/*
		 * HTTP-статус код ошибки.
		 */
		HttpStatus status,

		/*
		 * Временная метка возникновения ошибки в формате "yyyy-MM-dd HH:mm:ss".
		 * Позволяет отслеживать когда именно произошла ошибка.
		 */
		String timeStamp
) {
}