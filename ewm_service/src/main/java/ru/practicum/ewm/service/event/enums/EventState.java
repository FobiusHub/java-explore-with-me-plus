package ru.practicum.ewm.service.event.enums;

/**
 * Перечисление состояний события в системе.
 * Определяет жизненный цикл события от создания до публикации или отмены.
 *
 * <p>Состояния используются для управления видимостью событий и workflow модерации.</p>
 */
public enum EventState {
    /**
     * Событие ожидает модерации перед публикацией.
     * Находится на рассмотрении администратором системы.
     * Может быть переведено в состояния PUBLISHED или CANCELED.
     */
    PENDING,

    /**
     * Событие опубликовано и доступно для просмотра всеми пользователями.
     * Это финальное состояние, событие нельзя изменить после публикации.
     */
    PUBLISHED,

    /**
     * Событие отменено администратором или инициатором.
     * Не будет опубликовано и не доступно для просмотра.
     */
    CANCELED,
}