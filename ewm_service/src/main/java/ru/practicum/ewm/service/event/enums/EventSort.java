package ru.practicum.ewm.service.event.enums;

/**
 * Перечисление для определения способа сортировки событий.
 * Используется в публичном API для упорядочивания результатов поиска событий.
 *
 * <p>Определяет доступные варианты сортировки, которые могут быть использованы
 * при запросе списка событий через публичный API.</p>
 */
public enum EventSort {
    /**
     * Сортировка по дате проведения события в хронологическом порядке.
     * Ближайшие события отображаются первыми.
     *
     * <p>Используется по умолчанию при отсутствии указания способа сортировки.</p>
     */
    EVENT_DATE,

    /**
     * Сортировка по количеству просмотров события в порядке убывания.
     * Наиболее популярные события (с наибольшим числом просмотров) отображаются первыми.
     */
    VIEWS
}